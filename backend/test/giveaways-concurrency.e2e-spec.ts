import 'dotenv/config';
import { ConflictException } from '@nestjs/common';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '@prisma/client';
import { Pool } from 'pg';
import { GiveawaysService } from '../src/giveaways/giveaways.service';
import type { PrismaService } from '../src/prisma/prisma.service';

describe('GiveawaysService First Come concurrency (database)', () => {
  const connectionString = process.env.DATABASE_URL;
  const schema = `giveaway_concurrency_${process.pid}_${Date.now()}`;
  let admin: Pool;
  let prisma: PrismaClient;
  let service: GiveawaysService;

  beforeAll(async () => {
    if (!connectionString) throw new Error('DATABASE_URL is required');
    admin = new Pool({ connectionString });

    // This isolated schema prevents the concurrency test from reading or
    // changing development seed data in the public schema.
    await admin.query(`CREATE SCHEMA "${schema}"`);
    await admin.query(`
      CREATE TABLE "${schema}"."User" (
        "user_id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "email" varchar(255) NOT NULL UNIQUE,
        "first_name_en" varchar(100) NOT NULL,
        "last_name_en" varchar(100) NOT NULL,
        "first_name_th" varchar(100) NOT NULL,
        "last_name_th" varchar(100) NOT NULL,
        "password_hash" varchar(255) NOT NULL,
        "phone_number" varchar(20),
        "user_status" varchar(20) DEFAULT 'Active',
        "email_verified_at" timestamp(6),
        "isAdmin" boolean DEFAULT false,
        "created_at" timestamp(6) DEFAULT now()
      );
      CREATE TABLE "${schema}"."Giveaway_Post" (
        "giveaway_id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "item_name" varchar(255) NOT NULL,
        "quantity" integer NOT NULL DEFAULT 1,
        "description" text,
        "pickup_location" varchar(255) NOT NULL,
        "giver_id" integer NOT NULL REFERENCES "${schema}"."User"("user_id"),
        "allocation_method" varchar(20) NOT NULL,
        "pickup_deadline" timestamp(6),
        "register_deadline" timestamp(6),
        "giveaway_status" varchar(20) DEFAULT 'Active',
        "created_at" timestamp(6) DEFAULT now()
      );
      CREATE TABLE "${schema}"."Giveaway_Ticket" (
        "ticket_id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "giveaway_id" integer NOT NULL REFERENCES "${schema}"."Giveaway_Post"("giveaway_id"),
        "receiver_id" integer NOT NULL REFERENCES "${schema}"."User"("user_id"),
        "qr_token" varchar(255) UNIQUE,
        "ticket_status" varchar(20) DEFAULT 'Registered',
        "updated_at" timestamp(6) DEFAULT now(),
        UNIQUE ("giveaway_id", "receiver_id")
      );
    `);

    prisma = new PrismaClient({
      adapter: new PrismaPg(connectionString, { schema }),
    });
    service = new GiveawaysService(prisma as unknown as PrismaService);
  });

  afterAll(async () => {
    await prisma?.$disconnect();
    if (admin) {
      await admin.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
      await admin.end();
    }
  });

  it('grants exactly one final place when two users join simultaneously', async () => {
    const users = await Promise.all(
      ['giver', 'receiver-a', 'receiver-b'].map((name) =>
        prisma.user.create({
          data: {
            email: `${name}-${schema}@ku.th`,
            firstNameEn: name,
            lastNameEn: 'Concurrency',
            firstNameTh: name,
            lastNameTh: 'ทดสอบ',
            passwordHash: 'not-used',
            emailVerifiedAt: new Date(),
          },
        }),
      ),
    );
    const [giver, firstReceiver, secondReceiver] = users;
    const giveaway = await prisma.giveawayPost.create({
      data: {
        giverId: giver.userId,
        itemName: 'One remaining item',
        quantity: 1,
        pickupLocation: 'KU',
        allocationMethod: 'FirstCome',
        registerDeadline: new Date(Date.now() + 60_000),
      },
    });

    const results = await Promise.allSettled([
      service.join(String(giveaway.giveawayId), firstReceiver.userId),
      service.join(String(giveaway.giveawayId), secondReceiver.userId),
    ]);

    expect(
      results.filter((result) => result.status === 'fulfilled'),
    ).toHaveLength(1);
    const rejected = results.find((result) => result.status === 'rejected');
    const rejectionReason: unknown =
      rejected?.status === 'rejected' ? rejected.reason : null;
    expect(rejectionReason).toBeInstanceOf(ConflictException);
    await expect(
      prisma.giveawayTicket.count({
        where: { giveawayId: giveaway.giveawayId },
      }),
    ).resolves.toBe(1);
    await expect(
      prisma.giveawayPost.findUnique({
        where: { giveawayId: giveaway.giveawayId },
        select: { status: true },
      }),
    ).resolves.toEqual({ status: 'Closed' });
  });
});
